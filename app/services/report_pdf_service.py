    def _build_anomaly_section(self, dataset: Dict[str, Any], styles: dict) -> list:
        story = []
        story.append(Paragraph("Anomaly & Risk Findings", styles['section']))

        anom_summary = dataset.get("anomaly_summary", {})
        total_anom = anom_summary.get("total", 0)

        if total_anom == 0:
            story.append(Paragraph("No active financial anomalies or duplicate transaction risks detected for this reporting period.", styles['body']))
            story.append(Spacer(1, 10))
            return story

        anom_list = dataset.get("anomalies", [])
        anom_table_data = [[
            Paragraph("SEVERITY", styles['cell_header']),
            Paragraph("FINDING & DESCRIPTION", styles['cell_header']),
            Paragraph("AFFECTED DOCUMENT", styles['cell_header'])
        ]]

        for a in anom_list[:10]:
            sev = a.get("severity", "MEDIUM")
            sev_color = self.danger_red if sev in ["CRITICAL", "HIGH"] else self.warning_gold
            sev_p = Paragraph(f"<font color='{sev_color.hexval()}'><b>{sev}</b></font>", styles['cell'])

            desc_text = f"<b>{a.get('title')}</b><br/>{a.get('description')}"
            desc_p = Paragraph(desc_text, styles['cell'])
            doc_p = Paragraph(a.get('document_name', 'Document'), styles['cell'])

            anom_table_data.append([sev_p, desc_p, doc_p])

        anom_table = Table(anom_table_data, colWidths=[80, 310, 150])
        anom_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), self.bg_soft),
            ('LINEBELOW', (0,0), (-1,0), 1, self.brand_navy),
            ('LINEBELOW', (0,1), (-1,-1), 0.5, self.border_line),
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
            ('TOPPADDING', (0,0), (-1,-1), 5),
            ('BOTTOMPADDING', (0,0), (-1,-1), 5),
        ]))
        story.append(anom_table)
        story.append(Spacer(1, 10))

        return story

